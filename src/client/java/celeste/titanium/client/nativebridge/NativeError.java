package celeste.titanium.client.nativebridge;

public enum NativeError {
    OK(0), UNSUPPORTED_PLATFORM(1), NATIVE_RESOURCE_MISSING(2), NATIVE_EXTRACTION_FAILED(3),
    NATIVE_LOAD_FAILED(4), NO_DXGI_FACTORY6(5), NO_D3D11_ADAPTER(6), D3D11_CREATE_FAILED(7),
    ALREADY_SHUTDOWN(8), INTERNAL_ERROR(9), WGL_CONTEXT_FAILED(10), WGL_EXTENSION_MISSING(11),
    WGL_OPEN_DEVICE_FAILED(12), WGL_REGISTER_FAILED(13), WGL_LOCK_FAILED(14), WGL_UNLOCK_FAILED(15),
    WGL_UNREGISTER_FAILED(16), WGL_CLOSE_DEVICE_FAILED(17), WGL_DATA_MISMATCH(18),
    FRAME_TEXTURE_CREATE_FAILED(19), FRAME_TEXTURE_UNAVAILABLE(20), FRAME_INTEROP_INVALID_STATE(21),
    FRAME_INTEROP_CREATE_FAILED(22), FRAME_INTEROP_SEQUENCE_INVALID(23), FRAME_INTEROP_VALIDATION_FAILED(24),
    NGX_RUNTIME_INVALID(25), NGX_UNAVAILABLE(26), NGX_INVALID_STATE(27), NGX_INITIALIZE_FAILED(28),
    NGX_OPTIMAL_SETTINGS_FAILED(29), NGX_FEATURE_CREATE_FAILED(30), NGX_RELEASE_FAILED(31),
    NGX_EVALUATE_FAILED(32), NGX_OUTPUT_VALIDATION_FAILED(33);

    private final int code;
    NativeError(int code) { this.code = code; }
    public int code() { return code; }
    public static NativeError fromCode(int code) {
        for (NativeError value : values()) if (value.code == code) return value;
        return INTERNAL_ERROR;
    }
}
